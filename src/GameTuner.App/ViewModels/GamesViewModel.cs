using System.Collections.ObjectModel;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using GameTuner.App.Services;
using GameTuner.Core.Backup;
using GameTuner.Core.Games;
using GameTuner.Core.Performance;
using GameTuner.Core.Settings;

namespace GameTuner.App.ViewModels;

public sealed record SettingRow(string Label, string Value);

/// <summary>
/// "Игры" page: preset picker, universal advice and one card per supported game.
/// </summary>
public partial class GamesViewModel : ObservableObject
{
    private readonly SystemProfileService _profile;
    private readonly ISettingsService _settings;
    private readonly IBackupService _backups;
    private readonly IDialogService _dialogs;
    private bool _loaded;

    public GamesViewModel(SystemProfileService profile, ISettingsService settings, IGameLibrary library,
                          IBackupService backups, IDialogService dialogs)
    {
        _profile = profile;
        _settings = settings;
        _backups = backups;
        _dialogs = dialogs;

        foreach (var game in library.Profiles)
            Games.Add(new GameItemViewModel(game, this));

        _ = LoadAsync();
    }

    /// <summary>Index 0 = "Авто", 1..4 = Low..Ultra.</summary>
    public ObservableCollection<string> TierOptions { get; } = new();
    // -1 until the options are loaded: a ComboBox with no items can't select index 0.
    [ObservableProperty] private int _selectedTierIndex = -1;
    public ObservableCollection<string> Advice { get; } = new();
    public ObservableCollection<GameItemViewModel> Games { get; } = new();

    internal IBackupService Backups => _backups;
    internal IDialogService Dialogs => _dialogs;

    public PerformanceTier SelectedTier { get; private set; }

    private async Task LoadAsync()
    {
        var (_, tier) = await _profile.GetAsync();

        TierOptions.Add($"Авто — {GenericAdvice.TierName(tier.Tier)}");
        foreach (var t in Enum.GetValues<PerformanceTier>()) TierOptions.Add(GenericAdvice.TierName(t));

        SelectedTierIndex = _settings.Current.TierOverride is PerformanceTier manual ? (int)manual + 1 : 0;
        _loaded = true;
        await RefreshAsync();
    }

    /// <summary>Generated by [ObservableProperty]: runs whenever the preset combo changes.</summary>
    partial void OnSelectedTierIndexChanged(int value)
    {
        if (!_loaded || value < 0) return;
        _settings.Current.TierOverride = value == 0 ? null : (PerformanceTier)(value - 1);
        _settings.Save();
        _ = RefreshAsync();
    }

    private async Task RefreshAsync()
    {
        var (info, tierResult) = await _profile.GetAsync();
        SelectedTier = await _profile.GetEffectiveTierAsync();

        Advice.Clear();
        var effective = new TierResult { Tier = SelectedTier, Notes = tierResult.Notes };
        foreach (string line in GenericAdvice.Build(info, effective)) Advice.Add(line);

        foreach (var game in Games) game.Refresh(SelectedTier);
    }
}

/// <summary>One game card on the "Игры" page.</summary>
public partial class GameItemViewModel : ObservableObject
{
    private readonly GameProfile _game;
    private readonly GamesViewModel _owner;

    public GameItemViewModel(GameProfile game, GamesViewModel owner)
    {
        _game = game;
        _owner = owner;
    }

    public string Name => _game.Name;
    public ObservableCollection<SettingRow> Settings { get; } = new();

    [ObservableProperty] private string _status = "";
    // CanExecute of the commands follows these flags: the buttons enable/disable themselves.
    [ObservableProperty, NotifyCanExecuteChangedFor(nameof(ApplyCommand))] private bool _isFound;
    [ObservableProperty] private string _tips = "";
    [ObservableProperty, NotifyCanExecuteChangedFor(nameof(RestoreCommand))] private bool _canRestore;
    [ObservableProperty] private string _settingsHeader = "";

    public void Refresh(PerformanceTier tier)
    {
        int files = _game.FindConfigFiles().Count;
        IsFound = files > 0;
        Status = IsFound
            ? $"Найдено файлов настроек: {files}"
            : "Файл настроек не найден — игра не установлена или ни разу не запускалась";
        Tips = _game.GetTips(tier);
        CanRestore = _owner.Backups.ListBackups(_game.Id).Count > 0;

        Settings.Clear();
        foreach (var s in _game.GetSettings(tier)) Settings.Add(new SettingRow(s.Label, s.Value.Trim('"')));
        SettingsHeader = $"Что будет изменено ({Settings.Count})";
    }

    [RelayCommand(CanExecute = nameof(IsFound))]
    private async Task ApplyAsync()
    {
        var tier = _owner.SelectedTier;
        if (!await _owner.Dialogs.ConfirmAsync(
                $"Применить пресет к {Name}?",
                $"Пресет: {GenericAdvice.TierName(tier)}.\nПеред изменением будет сделан бэкап, откатить можно одной кнопкой.",
                "Применить"))
            return;

        // File work off the UI thread; the result comes back to it after await.
        var result = await Task.Run(() => _game.Apply(tier, _owner.Backups));

        string text = result.Message;
        if (result.MissingKeys.Count > 0)
            text += $"\n\nЭтих параметров нет в твоей версии игры (пропущены): {string.Join(", ", result.MissingKeys)}";

        await _owner.Dialogs.ShowAsync(result.Success ? "Готово" : "Не получилось", text);
        Refresh(tier);
    }

    [RelayCommand(CanExecute = nameof(CanRestore))]
    private async Task RestoreAsync()
    {
        if (_game.IsRunning())
        {
            await _owner.Dialogs.ShowAsync("Игра запущена", $"Сначала закрой {Name}.");
            return;
        }
        if (!await _owner.Dialogs.ConfirmAsync($"Откатить {Name}?", "Настройки вернутся к состоянию до последнего применения пресета.", "Откатить"))
            return;

        try
        {
            int restored = await Task.Run(() => _owner.Backups.RestoreLatest(_game.Id));
            await _owner.Dialogs.ShowAsync("Готово", $"Восстановлено файлов: {restored}.");
        }
        catch (Exception ex)
        {
            await _owner.Dialogs.ShowAsync("Ошибка отката", ex.Message);
        }
    }
}
